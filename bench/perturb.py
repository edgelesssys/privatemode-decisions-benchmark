"""Frozen label renamings, for telling understanding from recall.

The arms are trained *for* this task family and the standard sets are in
every training mix, so a benchmark that only reports accuracy cannot say
whether a number is competence or recall of the label string. This is the
cheap half of the answer: rename every option to a synonym that no training
set ever paired with these examples, change nothing else, and re-run.

A model that reads the state and reasons about the options should barely
move. A model that has memorised ``card_arrival`` as the answer to "where is
my card" should fall. The gap is the **memorisation delta**, reported per
arm per dataset.

Three properties make it evidence rather than decoration:

*The renaming is generated once and checked in.* ``perturbations/*.json``
is a reviewable artefact; a reader can see exactly what each option became
and object to any of it. Regenerating per run would let the perturbation
drift towards whatever produced the nicest result.

*It is generated by a model none of the arms is built on.* ``gpt-oss-120b``
writes the synonyms. GLM was the obvious first choice and the wrong one:
Privatemode's arm runs GLM, so synonyms suiting GLM's priors would have
biased the delta towards us. It also could not do the job -- GLM-5.3 reasons
natively and spent whole token budgets thinking without answering, which the
validation caught as eight datasets with nothing renamed.

*It is validated mechanically.* Names must be unique, non-empty, different
from the original, and no original may survive as a substring of its
replacement -- otherwise ``card_arrival`` becomes ``card_arrival_status``
and the memorised string is still there to be recognised.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from typing import TYPE_CHECKING

if TYPE_CHECKING:  # generating renamings needs a model; reading them does not
    from system_one import OpenAIClient

from .datasets import frozen
from .specs import BY_NAME, SPECS

CHUNK = 25
#: Not a model any arm is built on, which is the point; and unlike GLM-5.3
#: it answers this clerical request instead of reasoning until the token
#: budget is gone.
DEFAULT_MODEL = "gpt-oss-120b"
PROMPT = """You are relabelling a classification dataset.

Task the labels are for: {instructions}

Rewrite each label below as a short synonym that means exactly the same
thing but shares as few words with the original as possible. Keep the same
style (snake_case stays snake_case, a phrase stays a phrase). Never reuse
the original label or any distinctive word from it.

Reply with one line per label, formatted `original -> replacement`, and
nothing else.

Labels:
{labels}"""


def directory() -> Path:
    return Path(__file__).resolve().parent.parent / "perturbations"


def path_for(dataset: str) -> Path:
    return directory() / f"{dataset}-rename.json"


def load_rename(dataset: str) -> dict[str, str]:
    path = path_for(dataset)
    if not path.exists():
        raise FileNotFoundError(
            f"{path} is missing -- run `python -m bench.perturb {dataset}`. "
            "Renamings are generated once and checked in so the perturbation "
            "cannot drift between runs.")
    return json.loads(path.read_text())["rename"]


def _distinctive(name: str) -> set[str]:
    """The words a memorised label would be recognised by."""
    return {word for word in re.split(r"[^a-z0-9]+", name.lower())
            if len(word) > 3}


def propose(client: OpenAIClient, model: str, instructions: str,
            labels: list[str]) -> dict[str, str]:
    body, _ = client.post("/chat/completions", {
        "model": model,
        "messages": [{"role": "user", "content": PROMPT.format(
            instructions=instructions, labels="\n".join(labels))}],
        "max_tokens": 4000, "temperature": 0})
    choice = body["choices"][0]
    text = choice["message"].get("content") or ""
    if not text and choice.get("finish_reason") == "length":
        raise RuntimeError("the generator spent its whole budget without "
                           "answering; lower CHUNK or raise max_tokens")
    out: dict[str, str] = {}
    for line in text.splitlines():
        if "->" not in line:
            continue
        left, right = line.split("->", 1)
        left, right = left.strip().strip("`*-. "), right.strip().strip("`*-. ")
        if left in labels and right:
            out[left] = right
    return out


def problems(rename: dict[str, str], labels: list[str]) -> list[str]:
    out = []
    missing = [label for label in labels if label not in rename]
    if missing:
        out.append(f"{len(missing)} labels not renamed: "
                   f"{', '.join(missing[:5])}")
    values = list(rename.values())
    if len(set(values)) != len(values):
        duplicates = {v for v in values if values.count(v) > 1}
        out.append(f"replacements collide: {', '.join(sorted(duplicates)[:5])}")
    for original, replacement in rename.items():
        if replacement == original:
            out.append(f"{original!r} unchanged")
        elif _distinctive(original) & _distinctive(replacement):
            shared = ", ".join(sorted(_distinctive(original)
                                      & _distinctive(replacement)))
            out.append(f"{original!r} -> {replacement!r} still shares: {shared}")
    return out


def repair(client: OpenAIClient, model: str, instructions: str,
           rename: dict[str, str]) -> dict[str, str]:
    """Re-ask for the labels whose replacement collided or kept a word.

    Chunking means two chunks cannot see each other's answers, so a popular
    synonym gets proposed twice. Regenerating only the offenders, with the
    surviving replacements listed as taken, fixes that without disturbing
    the rest -- which matters because the file is checked in and a rerun
    that reshuffled every label would make the diff unreadable.
    """
    used = set(rename.values())
    broken = []
    for original, replacement in rename.items():
        collides = list(rename.values()).count(replacement) > 1
        if collides or replacement == original or (
                _distinctive(original) & _distinctive(replacement)):
            broken.append(original)
    if not broken:
        return rename
    keep = {k: v for k, v in rename.items() if k not in broken}
    taken = ", ".join(sorted(keep.values())) or "nothing yet"
    for start in range(0, len(broken), CHUNK):
        chunk = broken[start:start + CHUNK]
        fresh = propose(client, model,
                        f"{instructions}\n\nAlready taken, do not reuse: {taken}",
                        chunk)
        keep.update(fresh)
    return keep


def generate(dataset: str, client: OpenAIClient, model: str) -> dict:
    meta = frozen(dataset)
    labels = list(meta["options"])
    instructions = BY_NAME[dataset].instructions
    rename: dict[str, str] = {}
    for start in range(0, len(labels), CHUNK):
        chunk = labels[start:start + CHUNK]
        rename.update(propose(client, model, instructions, chunk))
    rename = repair(client, model, instructions, rename)
    return {"dataset": dataset, "model": model, "options": len(labels),
            "rename": rename, "problems": problems(rename, labels)}


def main(argv: list[str] | None = None) -> int:
    from .run import load_env

    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("names", nargs="*")
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--model", default=None)
    args = parser.parse_args(argv)

    load_env(Path(__file__).resolve().parent.parent / ".env")
    from system_one import OpenAIClient

    client = OpenAIClient.from_env()
    import os
    model = args.model or os.environ.get("PERTURB_MODEL", DEFAULT_MODEL)
    directory().mkdir(parents=True, exist_ok=True)

    names = args.names or [spec.name for spec in SPECS]
    failures = 0
    for name in names:
        path = path_for(name)
        if path.exists() and not args.force:
            print(f"  {name}: already generated", file=sys.stderr)
            continue
        try:
            report = generate(name, client, model)
        except Exception as error:
            print(f"! {name}: {type(error).__name__}: {error}", file=sys.stderr)
            failures += 1
            continue
        path.write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n")
        flags = report["problems"]
        print(f"  {name}: {len(report['rename'])}/{report['options']} renamed"
              + (f", {len(flags)} problems" if flags else "")
              + "".join(f"\n      ! {flag}" for flag in flags[:4]),
              file=sys.stderr)
        if flags:
            failures += 1
    client.close()
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
